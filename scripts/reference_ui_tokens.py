#!/usr/bin/env python3
"""Generate the reference client's fixed CSS aliases from its semantic tokens."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/design/reference-ui-tokens.json"
TARGET = ROOT / "crates/auth-axum/src/pages/tokens.css"


def declarations(values):
    return "\n".join(f"  --{key.replace('.', '-').replace('_', '-')}: {value};" for key, value in values.items())


def render():
    data = json.loads(SOURCE.read_text())
    dimensions = {key: f"{value / 16:g}rem" for key, value in data["dimensions"].items()}
    typography = {}
    for role, value in data["typography"].items():
        if isinstance(value, str):
            typography[f"font-{role}"] = value
        else:
            typography[f"font-{role}-size"] = f"{value['size'] / 16:g}rem"
            typography[f"font-{role}-line"] = f"{value['line_height'] / 16:g}rem"
            typography[f"font-{role}-weight"] = value["weight"]
    aliases = declarations({key: "var(--" + value + ")" for key, value in data["semantic_colors"].items()})
    component_tokens = declarations({key: "var(--" + value + ")" for key, value in data["component_tokens"].items()})
    return (
        "/* Generated by scripts/reference_ui_tokens.py; Basecoat owns the palette. */\n"
        f":root {{\n{declarations(dimensions)}\n{declarations(typography)}\n{aliases}\n{component_tokens}\n}}\n"
        "/* Configure the Vega focus/boundary color from its active foreground and background. */\n"
        ":root, :root.dark { --ring: color-mix(in oklch, var(--foreground) 60%, var(--background)); }\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("Reference UI token CSS is stale; run scripts/reference_ui_tokens.py")
    else:
        TARGET.write_text(expected)


if __name__ == "__main__":
    main()
