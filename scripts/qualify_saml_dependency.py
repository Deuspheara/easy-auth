#!/usr/bin/env python3
"""Run unchanged maintained SAML tests with the application's dependency versions.

No XML, signatures or security probes are generated by this script. Cargo runs
only the dependency's existing library, integration and documentation tests.
"""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

if __package__:
    from .check_saml_source import ROOT, SOURCE, check
else:
    from check_saml_source import ROOT, SOURCE, check

TREE = ["--edges", "normal,build", "--target", "all",
        "--prefix", "depth", "--format", "{p} features={f}", "--no-dedupe"]


def saml_subtree(output):
    """Select saml-rs and its descendants, excluding unrelated workspace crates."""
    packages = {}
    depth = None
    for line in output.splitlines():
        match = re.match(r"^(\d+)(\S+) v(\S+)", line)
        if not match:
            continue
        current, name, version = match.groups()
        current = int(current)
        if depth is not None and current <= depth:
            break
        if depth is None:
            if name != "saml-rs":
                continue
            depth = current
        features = line.split(" features=", 1)[1] if " features=" in line else ""
        packages[(name, version)] = tuple(sorted(filter(None, features.split(","))))
    if depth is None:
        raise ValueError("SAML package missing from dependency tree")
    if packages.get(("saml-rs", "0.6.1")) != ("crypto-aws-lc",):
        raise ValueError("unexpected SAML version or crypto feature selection")
    return packages


def cargo(arguments, cwd):
    result = subprocess.run(["cargo", *arguments], cwd=cwd, capture_output=True, text=True)
    if result.returncode:
        raise ValueError("Cargo dependency graph resolution failed")
    return result.stdout


def stage_workspace(staged, lock):
    for name in ["crates", "apps", "tests/support", "third-party/saml-rs"]:
        shutil.copytree(ROOT / name, staged / name)
    (staged / ".cargo").mkdir()
    shutil.copyfile(ROOT / ".cargo/config.toml", staged / ".cargo/config.toml")
    manifest = (ROOT / "Cargo.toml").read_text()
    excluded = 'exclude = ["third-party/saml-rs"]'
    if manifest.count(excluded) != 1 or manifest.count("members = [") != 1:
        raise ValueError("unexpected workspace layout")
    manifest = manifest.replace(excluded, "").replace(
        "members = [", 'members = ["third-party/saml-rs", ', 1)
    (staged / "Cargo.toml").write_text(manifest)
    # Workspace membership can add inactive optional lock entries. Resolve
    # normally, require identical active versions/features, then test locked.
    (staged / "Cargo.lock").write_bytes(lock)


def test_report(result, staged, lock, inventory, actual):
    # Never publish arbitrary test panic output: fixtures can contain XML or
    # keys. Emit only finite counts and Rust test identifiers on failure.
    output = result.stdout + result.stderr
    counts = [tuple(map(int, row)) for row in re.findall(
        r"test result: (?:ok|FAILED)\. (\d+) passed; (\d+) failed; (\d+) ignored", output)]
    failed_names = re.findall(r"^test ([A-Za-z0-9_:]+) \.\.\. FAILED$", output, re.MULTILINE)
    report = {
        "recorded_at": datetime.now(timezone.utc).isoformat(),
        "rustc": subprocess.check_output(["rustc", "-vV"], text=True).strip(),
        "reproducer_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "application_lock_sha256": hashlib.sha256(lock).hexdigest(),
        "cargo_config_sha256": hashlib.sha256(
            (staged / ".cargo/config.toml").read_bytes()).hexdigest(),
        "source_inventory_sha256": hashlib.sha256(
            inventory).hexdigest(),
        "qualification_lock_sha256": hashlib.sha256((staged / "Cargo.lock").read_bytes()).hexdigest(),
        "features": ["crypto-aws-lc"],
        "test_packages": ["easy-auth-core", "saml-rs"],
        "dependency_versions_match": True,
        "dependency_features_match": True,
        "normal_build_packages": [dict(name=n, version=v, features=list(actual[(n, v)]))
                                  for n, v in sorted(actual)],
        "exit_code": result.returncode,
        "passed": sum(row[0] for row in counts),
        "failed": sum(row[1] for row in counts),
        "ignored": sum(row[2] for row in counts),
        "failed_tests": failed_names,
        "test_groups": len(counts),
        "independent_security_approval": False,
    }
    return report


def qualify():
    check()
    lock = (ROOT / "Cargo.lock").read_bytes()
    inventory = (ROOT / "third-party/saml-rs-source.json").read_bytes()
    shipped = saml_subtree(cargo(["tree", "--locked", "-p", "easy-auth-core",
                                 "--features", "saml-verification", *TREE], ROOT))
    with tempfile.TemporaryDirectory(prefix="easy-auth-saml-qualification-") as directory:
        staged = Path(directory)
        stage_workspace(staged, lock)
        arguments = ["-p", "easy-auth-core", "-p", "saml-rs", "--no-default-features",
                     "--features", "easy-auth-core/saml-verification"]
        actual = saml_subtree(cargo(["tree", "-p", "easy-auth-core",
                                    "--features", "saml-verification", *TREE], staged))
        if actual != shipped:
            raise ValueError("qualification dependency versions differ from shipped SAML graph")
        environment = dict(os.environ, CARGO_INCREMENTAL="0")
        environment.setdefault("CARGO_TARGET_DIR", str(ROOT / "target"))
        result = subprocess.run(
            ["cargo", "test", "--locked", *arguments],
            cwd=staged, env=environment, capture_output=True, text=True,
        )
        if ((ROOT / "Cargo.lock").read_bytes() != lock
                or (ROOT / "third-party/saml-rs-source.json").read_bytes() != inventory
                or (ROOT / ".cargo/config.toml").read_bytes()
                != (staged / ".cargo/config.toml").read_bytes()):
            raise ValueError("application lock changed during qualification")
        report = test_report(result, staged, lock, inventory, actual)
        destination = ROOT / "target/saml-dependency-qualification.json"
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps({k: v for k, v in report.items() if k != "normal_build_packages"}))
        if result.returncode or not report["test_groups"] or report["failed"] or report["ignored"]:
            raise ValueError("existing SAML dependency tests did not pass")
    check()


if __name__ == "__main__":
    try:
        qualify()
    except (OSError, ValueError, subprocess.SubprocessError):
        print("Shipped-graph SAML dependency qualification: FAIL")
        raise SystemExit(1) from None
